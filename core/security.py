from passlib.context import CryptContext
from fastapi.security import OAuth2PasswordBearer
from jose import jwt
import os
from dotenv import load_dotenv

load_dotenv()


pwd_context = CryptContext(
    schemes=["bcrypt"],      # Используем алгоритм bcrypt для создания хеша пароля.
    deprecated="auto"        # Стандартная настройка passlib.
                              # Если в будущем алгоритм устареет, passlib сможет автоматически это определить.
)

SECRET_KEY = os.getenv("SECRET_KEY")
ALGORITHM = "HS256"

oauth2_scheme = OAuth2PasswordBearer(tokenUrl="/users/login")
# создаёт инструмент, который будет доставать JWT из запроса.
# JWT — сам токен, который подтверждает, что пользователь авторизован.

# Authorization: Bearer <JWT>
# Bearer — указывает, что дальше передаётся токен авторизации.
# Bearer — слово, которое говорит серверу: «вот мой токен авторизации»
# JWT — сам токен, который подтверждает, что пользователь авторизован.

# то есть вот что происходит 
# 1. Пользователь отправляет email + password
# 2. /users/login проверяет их
# 3. Если всё правильно — создаётся JWT
# 4. JWT возвращается пользователю

# При следующем запросе пользователь отправляет JWT:
# Authorization: Bearer <JWT>
# oauth2_scheme достаёт JWT из запроса

